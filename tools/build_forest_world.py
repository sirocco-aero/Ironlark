SHARED_SHAPES = {}
VISUAL_INSTANCES = []
COPIED_RESOURCES = {}


def copy_resource(source, out, convert_mesh=False):
    """Byte-identical assets get one URL, including across tree variants."""
    with source.open("rb") as stream:
        key = (hashlib.file_digest(stream, "sha256").hexdigest(), convert_mesh)
    if key not in COPIED_RESOURCES:
        url = "meshes/" + source.name
        if convert_mesh:
            copy_mesh(source, out / url)
        else:
            shutil.copyfile(source, out / url)
        COPIED_RESOURCES[key] = url
    return COPIED_RESOURCES[key]


def light_signature(build, out):
    """Invalidate canopy lighting when its actual geometry or alpha changes."""
    digest = hashlib.sha256(json.dumps(VISUAL_INSTANCES, sort_keys=True).encode())
    urls = {record[key] for record in VISUAL_INSTANCES for key in ("mesh", "texture")}
    paths = [out / url for url in sorted(urls)]
    paths += [
        build / "terrain.obj",
        Path(__file__).with_name("bake_forest_light.py"),
        Path(__file__).with_name("forest_terrain.py"),
    ]
    for path in paths:
        with path.open("rb") as stream:
            digest.update(hashlib.file_digest(stream, "sha256").digest())
    return digest.hexdigest()


def instance_node(**kw):
    """Share complete visual resources; transforms alone vary per instance."""
    x, y, z = enu([kw["x"], kw["y"], kw["z"]])
    ax, ay, az = enu([kw["ax"], kw["ay"], kw["az"]])
    sx, sy, sz = kw["sx"], kw["sz"], kw["sy"]
    mesh, tex = kw["mesh"], kw["tex"]
    normal = kw.get("normal", "")
    roughness = kw.get("roughness", "")
    VISUAL_INSTANCES.append(
        {
            "mesh": mesh,
            "texture": tex,
            "translation": [x, y, z],
            "rotation": [ax, ay, az, kw["ang"]],
            "scale": [sx, sy, sz],
        }
    )
    shadow = kw.get("shadow", False)
    key = (mesh, tex, normal, roughness, shadow)
    tag = "VISUAL_" + str(len(SHARED_SHAPES))
    if key in SHARED_SHAPES:
        shape = "USE " + SHARED_SHAPES[key]
    else:
        SHARED_SHAPES[key] = tag
        # All 53 source materials are alpha-hashed: mask texels, never blend them.
        normal_field = f'normalMap ImageTexture {{ url "{normal}" }}' if normal else ""
        roughness_field = (
            f'roughnessMap ImageTexture {{ url "{roughness}" }}' if roughness else ""
        )
        shape = f'''DEF {tag} Shape {{
          appearance PBRAppearance {{
            baseColorMap ImageTexture {{ url "{tex}" }}
            {normal_field}
            {roughness_field}
            roughness 0.9
            metalness 0
            alphaCutoff 0.5
          }}
          geometry Mesh {{ url "{mesh}" }}
          castShadows {"TRUE" if shadow else "FALSE"}
        }}'''
    return f"""Transform {{
      translation {x:.4f} {y:.4f} {z:.4f}
      rotation {ax:.6f} {ay:.6f} {az:.6f} {kw["ang"]:.6f}
      scale {sx:.5f} {sy:.5f} {sz:.5f}
      children [ {shape} ]
    }}"""


