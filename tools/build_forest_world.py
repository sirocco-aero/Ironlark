"""Build the Loiter pine-forest Webots world from export_forest.py output.

Usage:
    python3 build_forest_world.py --build <forest-build> --source <textures>
        --out <worlds/pine_forest>

Converts the cache's Y-up mesh convention to the flight stack's ENU frame.
Keeps authored placements and source UVs, shares geometry and materials, and
writes the world, camera/map metadata and build manifest.

Deterministic: all randomness is seeded. Tree collision beyond the home
vicinity arrives with the navigation phase (no autonomy reads it yet).
"""

